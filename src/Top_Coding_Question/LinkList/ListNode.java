package Top_Coding_Question.LinkList;



public  class ListNode {
    int val;
    Linked_List.ListNode next;

    ListNode() {}

    ListNode(int val) {
        this.val = val;
    }

    ListNode(int val, Linked_List.ListNode next) {
        this.val = val;
        this.next = next;
    }


}
